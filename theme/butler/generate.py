def herdr_block() -> str:
    out = [HERDR_BEGIN, "[theme]", 'name = "rose-pine-dawn"', "auto_switch = true", 'light_name = "rose-pine-dawn"', 'dark_name = "rose-pine"']
    for mode in ("light", "dark"):
        out += ["", f"[theme.custom.{mode}]"] + [f'{k} = "{v}"' for k, v in herdr_tokens(PAL[mode]).items()]
    out.append(HERDR_END)
    return "\n".join(out) + "\n"

def write_herdr_theme() -> None:
    """Replace the generated block in herdr's config.toml; the first time, replace the hand-written [theme] table with it."""
    path = CFG / "herdr/config.toml"
    text = path.read_text()
    if HERDR_BEGIN in text:
        text = re.sub(re.escape(HERDR_BEGIN) + r".*?" + re.escape(HERDR_END) + r"\n", lambda _: herdr_block(), text, flags=re.S)
    else:
        text = re.sub(r"\[theme\]\n.*?(?=\n\[|\Z)\n?", "", text, flags=re.S).rstrip() + "\n\n" + herdr_block()
    path.write_text(text)
    print("wrote", path)

