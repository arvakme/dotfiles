# ---------------------------------------------------------------- readability
def ghostty_opacity() -> float:
    """The window's `background-opacity` from the Ghostty config: the theme background is blended with whatever is behind the window."""
    try:
        return float(re.search(r"^background-opacity\s*=\s*([\d.]+)", (CFG / "ghostty/config").read_text(), re.M).group(1))
    except (OSError, AttributeError, ValueError):
        return 1.0

def blend(front: str, behind: str, alpha: float) -> str:
    return "#%02x%02x%02x" % tuple(round((f * alpha + b * (1 - alpha)) * 255) for f, b in zip(_rgb(front), _rgb(behind)))

def glass(bg: str, extreme: bool = False) -> list:
    """The theme background as seen through a translucent window: unchanged, and mixed with a dark and a light thing behind it. The default
    extremes (a dark-grey and a near-white window behind) are what a blurred desktop really offers; `extreme=True` uses pure black and white."""
    a = ghostty_opacity()
    dark, light = ("#000000", "#ffffff") if extreme else ("#303030", "#f0f0f0")
    return [bg, blend(bg, dark, a), blend(bg, light, a)]

def _rgb(h: str):
    h = h.lstrip("#")
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]

def luminance(h: str) -> float:
    r, g, b = (c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in _rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def contrast(a: str, b: str) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)

PAL = {mode: derive(RAW[mode]) for mode in ("dark", "light")}

def _lin(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

def _gamma(c: float) -> float:
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055

def to_oklch(h: str):
    r, g, b = (_lin(c) for c in _rgb(h))
    l, m, s = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b, 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b, 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
    l, m, s = (x ** (1 / 3) for x in (l, m, s))
    L, A, B = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s, 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
    return L, (A * A + B * B) ** 0.5, math.atan2(B, A)

def from_oklch(L: float, C: float, hue: float):
    """sRGB hex for the colour, or None when it falls outside the gamut."""
    A, B = C * math.cos(hue), C * math.sin(hue)
    l, m, s = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3, (L - 0.1055613458 * A - 0.0638541728 * B) ** 3, (L - 0.0894841775 * A - 1.2914855480 * B) ** 3
    rgb = (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)
    if any(c < -1e-4 or c > 1 + 1e-4 for c in rgb):
        return None
    return "#%02x%02x%02x" % tuple(round(min(1.0, max(0.0, _gamma(max(c, 0.0)))) * 255) for c in rgb)

def fit(color: str, backgrounds: list, minimum: float = 4.5, chroma: float = 0.0) -> str:
    """Keep the hue and the colourfulness, move only the lightness (OKLCH, so the colour does not turn electric or grey as it darkens) away from
    the backgrounds until the text reads on every one of them (WCAG ratio). `chroma` is a floor for coloured text; colours that do not fit the screen
    gamut at a lightness give up some chroma first."""
    L, C, hue = to_oklch(color)
    C = max(C, chroma)
    toward_light = sum(luminance(x) for x in backgrounds) / len(backgrounds) < 0.2
    out = color
    for _ in range(400):
        c = C
        while c > 0:
            out = from_oklch(L, c, hue)
            if out:
                break
            c -= 0.004
        else:
            out = from_oklch(L, 0.0, hue)
        if out and all(contrast(out, bg) >= minimum for bg in backgrounds):
            return out
        L = min(1.0, L + 0.004) if toward_light else max(0.0, L - 0.004)
    return out or color

# Levels of text, each its own step so hierarchy survives: the main text is far above the gate, notes sit just above it.
LEVELS = {"text": 7.0, "subtext": 6.0, "muted": 5.2, "note": 4.8, "colour": 4.8}
VIVID = 0.07

# ---------------------------------------------------------------- Ghostty
def ghostty(mode: str, p: dict) -> str:
    """A terminal theme. Text is fitted on the background and on its worst cases through the window's transparency (black or white behind);
    coloured text keeps its saturation, the grey `bright black` stays a visible note colour (the gate in `--check` is 4.5:1, WCAG AA)."""
    bg = glass(p["bg"])
    hue = lambda c, level="colour": fit(c, bg, LEVELS[level], VIVID)
    grey = lambda c, level: fit(c, bg, LEVELS[level])
    bright = lambda c: fit(c, bg, LEVELS["colour"], 0.12)
    ansi = [p["ice"] if luminance(p["bg"]) > 0.5 else p["selected"], hue(p["coral"]), hue(p["mint"]), hue(p["gold"]), hue(p["sky"]), hue(p["violet"]), hue(p["cyan"]),
            grey(p["steel"], "muted"), grey(p["comment"], "note"),
            bright(p["coral"]), bright(p["mint"]), bright(p["gold"]), bright(p["lavender"]), bright(p["violet"]), bright(p["glow"]),
            grey(p["ice"], "text")]
    lines = [f"# Butler {mode} — {HEADER}", f"background = {p['bg']}", f"foreground = {grey(p['ice'], 'text')}", f"cursor-color = {hue(p['cyan'])}", f"cursor-text = {p['bg']}",
             f"selection-background = {p['selected']}", f"selection-foreground = {fit(p['ice'], [p['selected']], 7.0)}"]
    lines += [f"palette = {i}={c}" for i, c in enumerate(ansi)]
    return "\n".join(lines) + "\n"

# ---------------------------------------------------------------- herdr
def herdr_tokens(p: dict) -> dict:
    """herdr colour tokens, one hue per place so the chrome is not a single colour: tab chip = accent (cyan), section headings and bullets = overlay0
    (violet), inactive items = subtext0 (sky), tab labels = overlay1 (mint), the selected item = text (the lightest), and the agent states take the other
    colours. The focused tab's label is drawn in `surface_dim` on the accent (herdr uses it as the chip text while panel_bg is `reset`), so it is
    the theme background, never `reset` (that would be the terminal's own foreground on the accent). The sidebar, the tab strip and the panes use `reset` (the terminal's own background), so Ghostty's transparency and blur show through;
    only the selected row has a colour of its own (Ghostty keeps cells with an explicit background opaque). Text is fitted on the terminal background
    as seen through the glass, and on the selected row."""
    active = blend(p["violet"], p["selected"], 0.10)
    surfaces = glass(p["bg"]) + [active]
    hue = lambda c: fit(c, surfaces, LEVELS["colour"], VIVID)
    return {"accent": hue(p["cyan"]), "panel_bg": "reset", "sidebar_bg": "reset", "active_row_bg": active, "selection_bg": active,
            "surface0": p["panel"], "surface1": p["line"], "surface_dim": p["bg"], "overlay0": hue(p["violet"]), "overlay1": hue(p["mint"]),
            "text": fit(p["ice"], surfaces, LEVELS["text"]), "subtext0": hue(p["sky"]), "mauve": hue(p["violet"]), "green": hue(p["mint"]), "yellow": hue(p["gold"]),
            "red": hue(p["coral"]), "blue": hue(p["sky"]), "teal": hue(p["glow"]), "peach": hue(p["peach"])}

